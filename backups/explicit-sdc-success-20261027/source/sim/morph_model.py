from dataclasses import dataclass
from enum import IntFlag
from typing import Sequence

PIN_WIDTH = 8
PIN_MASK = (1 << PIN_WIDTH) - 1
TIMER_MAX = 65535


class Event(IntFlag):
    NONE = 0
    RISE = 1 << 0
    FALL = 1 << 1
    TIMEOUT = 1 << 2
    RX_READY = 1 << 3
    EXTERNAL = 1 << 4


@dataclass(frozen=True)
class Action:
    data_mask: int = 0
    data_value: int = 0
    oe_mask: int = 0
    oe_value: int = 0
    wait_cycles: int | None = None

    def __post_init__(self):
        for name in ("data_mask", "data_value", "oe_mask", "oe_value"):
            value = getattr(self, name)
            if not isinstance(value, int) or not 0 <= value <= PIN_MASK:
                raise ValueError(f"{name} must be an 8-bit unsigned value")

        if self.wait_cycles is not None:
            if not isinstance(self.wait_cycles, int):
                raise ValueError("wait_cycles must be an integer or None")
            if not 0 <= self.wait_cycles <= TIMER_MAX:
                raise ValueError("wait_cycles must be between 0 and 65535")


@dataclass(frozen=True)
class Transition:
    state: int
    require_events: Event = Event.NONE
    forbid_events: Event = Event.NONE
    input_mask: int = 0
    input_value: int = 0
    rise_mask: int = 0
    fall_mask: int = 0
    next_state: int | None = None
    action: Action = Action()
    name: str = "transition"


@dataclass(frozen=True)
class Snapshot:
    cycle: int
    sampled_pins: int
    rising_pins: int
    falling_pins: int
    events: Event
    state_before: int
    state_after: int
    pin_data: int
    output_enable: int
    wait_remaining: int
    selected_transition: str | None
    fault: str | None


class MachineModel:
    def __init__(
        self,
        transitions: Sequence[Transition],
        state_count: int,
        reset_state: int = 0,
        open_drain_mask: int = 0,
    ):
        if state_count < 1:
            raise ValueError("state_count must be positive")
        if not 0 <= reset_state < state_count:
            raise ValueError("reset_state is outside the state range")
        if not 0 <= open_drain_mask <= PIN_MASK:
            raise ValueError("open_drain_mask must be 8-bit")

        self.transitions = tuple(transitions)
        self.state_count = state_count
        self.reset_state = reset_state
        self.open_drain_mask = open_drain_mask

        for transition in self.transitions:
            if not 0 <= transition.state < state_count:
                raise ValueError("transition source state is invalid")
            if transition.next_state is not None:
                if not 0 <= transition.next_state < state_count:
                    raise ValueError("transition destination state is invalid")
            for name in ("input_mask", "input_value", "rise_mask", "fall_mask"):
                value = getattr(transition, name)
                if not 0 <= value <= PIN_MASK:
                    raise ValueError(f"{name} must be 8-bit")

        self.cycle = 0
        self._reset_registers()

    def _reset_registers(self):
        self.state = self.reset_state
        self.pin_data = 0
        self.output_enable = 0
        self.wait_remaining = 0
        self.previous_sample = 0
        self.sync_stage1 = 0
        self.sync_stage2 = 0
        self.fault = None

    def _matches(
        self,
        transition: Transition,
        events: Event,
        sampled_pins: int,
        rising_pins: int,
        falling_pins: int,
    ) -> bool:
        if transition.state != self.state:
            return False

        if (events & transition.require_events) != transition.require_events:
            return False

        if events & transition.forbid_events:
            return False

        if (
            sampled_pins & transition.input_mask
        ) != (transition.input_value & transition.input_mask):
            return False

        if transition.rise_mask and not (rising_pins & transition.rise_mask):
            return False

        if transition.fall_mask and not (falling_pins & transition.fall_mask):
            return False

        return True

    def step(
        self,
        raw_pins: int = 0,
        external_events: Event = Event.NONE,
        rst_n: bool = True,
    ) -> Snapshot:
        if not isinstance(raw_pins, int) or not 0 <= raw_pins <= PIN_MASK:
            raise ValueError("raw_pins must be an 8-bit unsigned value")

        external_events = Event(external_events)
        allowed_external = Event.RX_READY | Event.EXTERNAL
        if external_events & ~allowed_external:
            raise ValueError("RISE, FALL and TIMEOUT are generated by the model")

        self.cycle += 1
        state_before = self.state

        if not rst_n:
            self._reset_registers()
            return Snapshot(
                cycle=self.cycle,
                sampled_pins=0,
                rising_pins=0,
                falling_pins=0,
                events=Event.NONE,
                state_before=state_before,
                state_after=self.state,
                pin_data=self.pin_data,
                output_enable=self.output_enable,
                wait_remaining=self.wait_remaining,
                selected_transition=None,
                fault=self.fault,
            )

        sampled_pins = self.sync_stage2
        rising_pins = sampled_pins & ~self.previous_sample & PIN_MASK
        falling_pins = self.previous_sample & ~sampled_pins & PIN_MASK

        events = external_events
        if rising_pins:
            events |= Event.RISE
        if falling_pins:
            events |= Event.FALL

        if self.wait_remaining > 0:
            self.wait_remaining -= 1
            if self.wait_remaining == 0:
                events |= Event.TIMEOUT

        selected = None

        if self.fault is None:
            for transition in self.transitions:
                if self._matches(
                    transition,
                    events,
                    sampled_pins,
                    rising_pins,
                    falling_pins,
                ):
                    selected = transition
                    break

        if self.fault is not None:
            self.output_enable = 0

        elif selected is not None:
            action = selected.action

            new_data = (
                (self.pin_data & ~action.data_mask)
                | (action.data_value & action.data_mask)
            ) & PIN_MASK

            new_oe = (
                (self.output_enable & ~action.oe_mask)
                | (action.oe_value & action.oe_mask)
            ) & PIN_MASK

            illegal_high = new_data & new_oe & self.open_drain_mask

            if illegal_high:
                self.fault = "OPEN_DRAIN_DRIVE_HIGH"
                self.output_enable = 0
            else:
                self.pin_data = new_data
                self.output_enable = new_oe

                if selected.next_state is not None:
                    self.state = selected.next_state

                if action.wait_cycles is not None:
                    self.wait_remaining = action.wait_cycles

        self.previous_sample = sampled_pins
        self.sync_stage2 = self.sync_stage1
        self.sync_stage1 = raw_pins

        return Snapshot(
            cycle=self.cycle,
            sampled_pins=sampled_pins,
            rising_pins=rising_pins,
            falling_pins=falling_pins,
            events=events,
            state_before=state_before,
            state_after=self.state,
            pin_data=self.pin_data,
            output_enable=self.output_enable,
            wait_remaining=self.wait_remaining,
            selected_transition=selected.name if selected else None,
            fault=self.fault,
        )
